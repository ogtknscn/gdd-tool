export function t(language: Language, key: string, vars?: Record<string, string | number>): string {
  const template = translations[language][key] ?? translations.tr[key] ?? key;
  if (!vars) return template;
  return Object.entries(vars).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template);
}
